/**
 * Home = an action surface. It shows only what needs the user's attention
 * (enable / select / update), collapses to a single "✓ all set" line when
 * everything is fine, and offers a compact quick-launcher row. The physical
 * key-event logger now lives in Settings → Advanced → Diagnostics.
 */
@Composable
fun KeyboardSetupScreen(
    modifier: Modifier = Modifier,
    activity: MainActivity
) {
    val context = LocalContext.current

    var isPhysiBoardEnabled by remember { mutableStateOf(false) }
    var isPhysiBoardSelected by remember { mutableStateOf(false) }
    var enabledLanguageCount by remember { mutableStateOf(0) }
    var updateInfo by remember { mutableStateOf<HomeUpdateInfo?>(null) }

    // Smart-backlight readiness — surfaced on the Backlight tile so the home can flag
    // when the light is enabled but has never been configured (the persistent value has
    // not been written yet). Once configured it survives reboots, so live Wireless-debugging
    // state is irrelevant to the badge.
    var devicePaired by remember { mutableStateOf(true) }

    fun refreshStatus() {
        checkImeStatus(context) { enabled, selected ->
            isPhysiBoardEnabled = enabled
            isPhysiBoardSelected = selected
        }
        enabledLanguageCount = getEnabledInputLanguageCount(context)
        devicePaired = brobata.physiboard.inputmethod.EmbeddedAdbShell.isPaired(context)
    }

    // Initial IME + language + backlight status
    LaunchedEffect(Unit) { refreshStatus() }

    // Refresh status periodically while the screen is visible (kept from the old home).
    LaunchedEffect(Unit) {
        while (true) {
            delay(2000)
            refreshStatus()
        }
    }

    // The tile flags the one pairing every privileged tool depends on, not one feature's state.
    // Flagging the backlight instead meant a user who had never switched the backlight on was
    // never told that the toolbox needed setting up at all.
    // The Status tile's summary: the two checks the Status screen leads with.
    val setupComplete = isPhysiBoardEnabled && isPhysiBoardSelected
    val backlightNeedsAttention = !devicePaired

    // Request notification permission (Android 13+)
    val requestPermissionLauncher = rememberLauncherForActivityResult(
        contract = ActivityResultContracts.RequestPermission()
    ) { /* result ignored */ }
    LaunchedEffect(Unit) {
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.TIRAMISU) {
            if (!NotificationHelper.hasNotificationPermission(context)) {
                requestPermissionLauncher.launch(android.Manifest.permission.POST_NOTIFICATIONS)
            }
        }
    }

    // Automatic update check on open. Existing dialog behaviour is preserved AND
    // the result is surfaced as an action card.
    if (shouldUseGithubUpdateChecks(context)) {
        LaunchedEffect(Unit) {
            checkForUpdate(
                context = context,
                currentVersion = BuildConfig.VERSION_NAME,
                releaseChannel = BuildConfig.RELEASE_CHANNEL,
                ignoreDismissedReleases = true
            ) { hasUpdate, latestVersion, downloadUrl, releasePageUrl ->
                if (hasUpdate && latestVersion != null) {
                    updateInfo = HomeUpdateInfo(latestVersion, downloadUrl, releasePageUrl)
                    showUpdateDialog(context, latestVersion, downloadUrl, releasePageUrl)
                }
            }
        }
    }

    val launchSettings: (String?) -> Unit = { destination ->
        val intent = Intent(context, SettingsActivity::class.java)
        if (destination != null) {
            intent.putExtra(SettingsActivity.EXTRA_DESTINATION, destination)
        }
        context.startActivity(intent)
        (context as? Activity)?.let { act ->
            if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.UPSIDE_DOWN_CAKE) {
                act.overrideActivityTransition(
                    Activity.OVERRIDE_TRANSITION_OPEN,
                    R.anim.slide_in_from_right,
                    0
                )
            } else {
                @Suppress("DEPRECATION")
                act.overridePendingTransition(R.anim.slide_in_from_right, 0)
            }
        }
    }

    val launchKeyboardTheme: () -> Unit = {
        launchSettings(SettingsActivity.DESTINATION_KEYBOARD_THEME)
    }

    Column(
        modifier = modifier
            .fillMaxWidth()
            .verticalScroll(rememberScrollState()),
        verticalArrangement = Arrangement.spacedBy(12.dp)
    ) {
        // Terminal header — physiboard:~$ prompt + blinking cursor.
        CustomTopBar(
            modifier = Modifier.fillMaxWidth()
        )

        Column(
            modifier = Modifier
                .fillMaxWidth()
                .padding(horizontal = 16.dp),
            verticalArrangement = Arrangement.spacedBy(10.dp)
        ) {
            val update = updateInfo

            // Setup action cards — shown only when action is required.
            when {
                !isPhysiBoardEnabled -> HomeActionCard(
                    icon = Icons.Filled.Keyboard,
                    title = stringResource(R.string.home_action_enable_title),
                    subtitle = stringResource(R.string.home_action_enable_subtitle),
                    onClick = {
                        context.startActivity(Intent(Settings.ACTION_INPUT_METHOD_SETTINGS))
                    }
                )
                !isPhysiBoardSelected -> HomeActionCard(
                    icon = Icons.Filled.Keyboard,
                    title = stringResource(R.string.home_action_select_title),
                    subtitle = stringResource(R.string.home_action_select_subtitle),
                    onClick = {
                        val imm = context.getSystemService(Context.INPUT_METHOD_SERVICE) as InputMethodManager
                        imm.showInputMethodPicker()
                    }
                )
            }

            if (update != null) {
                HomeActionCard(
                    icon = Icons.Filled.Update,
                    title = stringResource(R.string.home_action_update_title),
                    subtitle = stringResource(R.string.home_action_update_subtitle, update.version),
                    onClick = {
                        showUpdateDialog(context, update.version, update.downloadUrl, update.releasePageUrl)
                    }
                )
            }

            // All-clear: a single quiet mono line.
            if (isPhysiBoardEnabled && isPhysiBoardSelected && update == null) {
                Text(
                    text = stringResource(R.string.home_all_set),
                    style = MaterialTheme.typography.bodyMedium,
                    fontFamily = FontFamily.Monospace,
                    color = MaterialTheme.colorScheme.primary,
                    modifier = Modifier.padding(vertical = 4.dp)
                )
            }

            // Quick-launcher tiles. Wrap to 2 columns so they fit the square screen.
            val backlightSublabel = if (backlightNeedsAttention) {
                stringResource(R.string.home_tile_backlight_needs_setup)
            } else null
            // Doors, each opening on something the others do not contain. The backlight warning
            // rides the Device tile rather than getting its own, so "needs setup" stays visible
            // without putting the same destination on two screens. Status and Status Bar Theme
            // were added in 2.0: the first answers "why is nothing working", the second is the
            // thing people reach for most often.
            val tiles = buildList {
                add(
                    HomeTile(
                        icon = Icons.Filled.Build,
                        label = stringResource(R.string.toolbox_title),
                        attention = backlightNeedsAttention,
                        sublabel = backlightSublabel,
                        onClick = { launchSettings(SettingsActivity.DESTINATION_TOOLBOX) }
                    )
                )
                add(
                    HomeTile(
                        icon = Icons.Filled.Keyboard,
                        label = stringResource(R.string.keyboard_hub_title),
                        onClick = { launchSettings(SettingsActivity.DESTINATION_KEYBOARD_HUB) }
                    )
                )
                add(
                    HomeTile(
                        icon = Icons.Filled.Palette,
                        label = stringResource(R.string.status_bar_theme_title),
                        onClick = { launchSettings(SettingsActivity.DESTINATION_KEYBOARD_THEME) }
                    )
                )
                add(
                    HomeTile(
                        icon = Icons.Filled.CheckCircle,
                        label = stringResource(R.string.settings_category_status),
                        // The tile says whether anything is wrong, so the answer is visible without
                        // opening it. Same two checks the Status screen leads with.
                        attention = !setupComplete,
                        sublabel = if (setupComplete) {
                            stringResource(R.string.home_tile_status_ok)
                        } else {
                            stringResource(R.string.home_tile_status_needs_setup)
                        },
                        onClick = { launchSettings(SettingsActivity.DESTINATION_STATUS) }
                    )
                )
                add(
                    HomeTile(
                        icon = Icons.Filled.MoreHoriz,
                        label = stringResource(R.string.extras_title),
                        onClick = { launchSettings(SettingsActivity.DESTINATION_EXTRAS) }
                    )
                )
                add(
                    HomeTile(
                        icon = Icons.Filled.Settings,
                        label = stringResource(R.string.home_tile_all_settings),
                        onClick = { launchSettings(null) }
                    )
                )
            }

            tiles.chunked(2).forEach { rowTiles ->
                Row(
                    modifier = Modifier
                        .fillMaxWidth()
                        .height(IntrinsicSize.Min),
                    horizontalArrangement = Arrangement.spacedBy(10.dp)
                ) {
                    rowTiles.forEach { tile ->
                        HomeQuickTile(
                            icon = tile.icon,
                            label = tile.label,
                            attention = tile.attention,
                            sublabel = tile.sublabel,
                            modifier = Modifier.weight(1f),
                            onClick = tile.onClick
                        )
                    }
                    // Keep tile width consistent on an odd final row.
                    if (rowTiles.size == 1) Spacer(modifier = Modifier.weight(1f))
                }
            }
        }
    }
}

@Composable
