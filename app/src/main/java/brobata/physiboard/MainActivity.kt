                imageVector = Icons.AutoMirrored.Filled.ArrowForward,
                contentDescription = null,
                tint = MaterialTheme.colorScheme.onSurfaceVariant,
                modifier = Modifier.size(18.dp)
            )
        }
    }
}

@Composable
private fun HomeQuickTile(
    icon: androidx.compose.ui.graphics.vector.ImageVector,
    label: String,
    onClick: () -> Unit,
    modifier: Modifier = Modifier,
    attention: Boolean = false,
    sublabel: String? = null
) {
    Box(modifier = modifier) {
        Surface(
            modifier = Modifier
                .fillMaxWidth()
                // Fill the row height (rows use IntrinsicSize.Min) so both tiles in a row
                // match — the Backlight "needs setup" sublabel no longer makes it taller than
                // its row-mate — while staying compact/content-sized so the grid fits.
                .fillMaxHeight()
                .heightIn(min = 64.dp)
                .clickable(onClick = onClick),
            color = MaterialTheme.colorScheme.surface,
            shape = MaterialTheme.shapes.medium
        ) {
            Column(
                modifier = Modifier
                    .fillMaxWidth()
                    .padding(horizontal = 8.dp, vertical = 12.dp),
                verticalArrangement = Arrangement.spacedBy(6.dp, Alignment.CenterVertically),
                horizontalAlignment = Alignment.CenterHorizontally
            ) {
                Icon(
                    imageVector = icon,
                    contentDescription = null,
                    tint = MaterialTheme.colorScheme.primary,
                    modifier = Modifier.size(24.dp)
                )
                Text(
                    text = label,
                    style = MaterialTheme.typography.labelLarge,
                    fontFamily = FontFamily.Monospace,
                    fontWeight = FontWeight.Medium
                )
                if (sublabel != null) {
                    Text(
                        text = sublabel,
                        style = MaterialTheme.typography.labelSmall,
                        fontFamily = FontFamily.Monospace,
                        color = MaterialTheme.colorScheme.primary,
                        maxLines = 1,
                        overflow = TextOverflow.Ellipsis
                    )
                }
            }
        }
        // Amber attention dot — the home's signal that the backlight needs a fix.
        if (attention) {
            Box(
                modifier = Modifier
                    .align(Alignment.TopEnd)
                    .padding(8.dp)
                    .size(9.dp)
                    .background(MaterialTheme.colorScheme.primary, CircleShape)
            )
        }
    }
}

/**
 * Counts the distinct language codes across PhysiBoard's enabled IME subtypes.
 * Used to decide whether the adaptive Language quick-tile is worth showing.
 */
private fun getEnabledInputLanguageCount(context: Context): Int {
    return try {
        val imm = context.getSystemService(Context.INPUT_METHOD_SERVICE) as? InputMethodManager
            ?: return 0
        val imeInfo = imm.enabledInputMethodList.find {
            it.packageName == ImeIdentity.packageName &&
                it.serviceName == ImeIdentity.serviceClassName
        } ?: return 0
        val enabledSubtypes = imm.getEnabledInputMethodSubtypeList(imeInfo, true)
        enabledSubtypes.mapNotNull { subtype ->
            val locale = subtype.localeString()
            if (!locale.isNullOrEmpty()) {
                try {
                    Locale.forLanguageTag(locale.replace("_", "-")).language.lowercase()
                } catch (_: Exception) {
                    locale.split("_").firstOrNull()?.lowercase()
                }
            } else {
                null
            }
        }.toSet().size
    } catch (e: Exception) {
        android.util.Log.e("MainActivity", "Error counting enabled input languages", e)
        0
    }
}

/**
 * Checks if PhysiBoard IME is enabled and selected.
 * Uses InputMethodManager for Android 14+ compatibility.
 */
private fun checkImeStatus(
    context: Context,
    callback: (enabled: Boolean, selected: Boolean) -> Unit
) {
    try {
        val imm = context.getSystemService(Context.INPUT_METHOD_SERVICE) as InputMethodManager
        val physiBoardPackageName = ImeIdentity.packageName

        // Check if PhysiBoard is enabled using InputMethodManager
        val enabledInputMethods = imm.enabledInputMethodList
        val isEnabled = enabledInputMethods.any { inputMethodInfo ->
            inputMethodInfo.packageName == physiBoardPackageName ||
            ImeIdentity.matchesImeId(inputMethodInfo.id)
        }

        // Check if PhysiBoard is selected
        var isSelected = false
        if (isEnabled) {
            try {
                val defaultInputMethod = android.provider.Settings.Secure.getString(
                    context.contentResolver,
                    android.provider.Settings.Secure.DEFAULT_INPUT_METHOD
                ) ?: ""
                isSelected = ImeIdentity.matchesImeId(defaultInputMethod)
            } catch (e: SecurityException) {
                // On Android 14+ (API 34+) with targetSdk 36, we can't read this setting.
                try {
                    val currentSubtype = imm.currentInputMethodSubtype
                    if (currentSubtype != null) {
                        val allInputMethods = imm.inputMethodList
                        val physiBoardInputMethod = allInputMethods.find {
                            it.packageName == physiBoardPackageName || ImeIdentity.matchesImeId(it.id)
                        }
                        isSelected = physiBoardInputMethod != null && enabledInputMethods.size == 1
                    } else {
                        isSelected = false
                    }
                } catch (e2: Exception) {
                    isSelected = false
                }
            } catch (e: Exception) {
                isSelected = false
            }
        }

        callback(isEnabled, isSelected)
    } catch (e: Exception) {
        android.util.Log.e("MainActivity", "Error checking IME status", e)
        callback(false, false)
    }
}

/**
 * One-time notice on a Titan 2 that is not an Elite: the keyboard should work, but nothing has
 * been tested against that hardware and it is not supported.
 */
@Composable
private fun UntestedDeviceNotice() {
    val context = LocalContext.current
    var show by remember {
        mutableStateOf(
            brobata.physiboard.inputmethod.DeviceSpecific.isUntestedTitanDevice() &&
                SettingsManager.shouldShowUntestedDeviceNotice(context)
        )
    }
    if (!show) return
    AlertDialog(
        onDismissRequest = {
            SettingsManager.markUntestedDeviceNoticeSeen(context)
            show = false
        },
        title = { Text(stringResource(R.string.untested_device_notice_title)) },
        text = { Text(stringResource(R.string.untested_device_notice_message)) },
        confirmButton = {
            TextButton(onClick = {
                SettingsManager.markUntestedDeviceNoticeSeen(context)
                show = false
            }) { Text(stringResource(R.string.untested_device_notice_dismiss)) }
        }
    )
}

/**
 * Shown once to a user upgrading from 1.x. The rename changes the input method's component name,
 * which Android treats as a different keyboard, so it disables and deselects PhysiBoard - and from
 * the user's side that looks exactly like the update broke it. Say what happened, and offer the
 * old settings back for anyone who preferred them.
 */
@Composable
private fun MigrationNotice() {
    val context = LocalContext.current
    var show by remember { mutableStateOf(SettingsMigration.shouldShowMigrationNotice(context)) }
    var restored by remember { mutableStateOf(false) }
    if (!show) return

    fun dismiss() {
        SettingsMigration.markMigrationNoticeSeen(context)
        show = false
    }

    AlertDialog(
        onDismissRequest = ::dismiss,
        title = { Text(stringResource(R.string.v2_notice_title)) },
        text = {
            Text(
                if (restored) stringResource(R.string.v2_notice_restored)
                else stringResource(R.string.v2_notice_message)
            )
        },
        confirmButton = {
            TextButton(onClick = ::dismiss) { Text(stringResource(R.string.v2_notice_dismiss)) }
        },
        dismissButton = {
            if (!restored) {
                TextButton(onClick = {
                    SettingsMigration.restoreLegacySettings(context)
                    restored = true
                }) { Text(stringResource(R.string.v2_notice_restore)) }
            }
        }
    )
}
